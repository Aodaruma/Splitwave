import { expect, test } from 'bun:test';
import { displayFrame, editorHarness, fixture } from './helpers/editor_performance';
import { copyDefinition, definition, scopeAt } from '../src/lib/modules/pipeline/groups';
import { groupView } from '../src/lib/modules/flow/utils/group_view';
import { PIPELINE_VERSION } from '../src/lib/modules/pipeline/version';

test('movement, selection and measurement do not snapshot for group labels or routing; explicit snapshots keep current geometry', () => {
	const editor = editorHarness();
	const before = editor.getSnapshot();
	const signature = editor.routingSignature();
	const counts = { ...editor.counts };
	for (let frame = 0; frame < 120; frame++) displayFrame(editor, frame);
	editor.scope.nodes = editor.scope.nodes.map((n) => ({ ...n, measured: { width: 220, height: 150 }, width: 220, height: 150 }));
	expect(editor.routingSignature()).toBe(signature);
	expect(editor.groupUsage('leaf')).toBe(12);
	expect(editor.counts).toEqual(counts);
	const after = editor.getSnapshot();
	expect(definition(after.groups!, 'root').nodes[0].position).toEqual({ x: 120, y: 119 });
	expect(definition(before.groups!, 'root').nodes[0].position).toEqual({ x: 0, y: 0 });
	expect(editor.counts.snapshots).toBe(counts.snapshots + 1);
});

test('usage reads unsaved additions, deletions, replacements and nested linked occurrences without mutating documents', () => {
	const data = fixture(2, 2);
	const leaf = definition(data.doc, 'leaf');
	data.doc.definitions.child = { id: 'child', name: 'Child', revision: 0, nodes: [], edges: [], inputs: [], outputs: [] };
	leaf.nodes.push({ id: 'child-instance', kind: 'group', data: { definition: 'child' }, position: { x: 0, y: 0 } });
	data.library.pipelines.other = { ...data.pipeline, id: 'other', groups: structuredClone(data.doc) };
	data.library.pipelines.future = { ...data.pipeline, id: 'future', version: PIPELINE_VERSION + 1 };
	const editor = editorHarness(undefined, data);
	const original = structuredClone(data);
	expect(editor.groupUsage('leaf')).toBe(4);
	expect(editor.groupUsage('child')).toBe(4);
	editor.scope.nodes = editor.scope.nodes.slice(1);
	expect(editor.groupUsage('leaf')).toBe(3);
	expect(editor.groupUsage('child')).toBe(3);
	editor.scope.nodes.push({ ...editor.scope.nodes[0], id: 'unsaved-copy' });
	expect(editor.groupUsage('child')).toBe(4);
	editor.scope.nodes[1] = { ...editor.scope.nodes[1], data: { definition: 'child' } };
	expect(editor.groupUsage('leaf')).toBe(3);
	expect(editor.groupUsage('child')).toBe(4);
	editor.scope.groupPath = ['g0'];
	Object.assign(editor.scope, groupView(data.doc, editor.scope.groupPath));
	editor.scope.nodes.push({ ...editor.scope.nodes.find((n) => n.type === 'group')!, id: 'second-child' });
	expect(editor.groupUsage('child')).toBe(6);
	expect(data).toEqual(original);
	expect(editor.counts.snapshots).toBe(0);
});

test('routing invalidates for data, wiring, topology, document replacement and library refresh while ignoring cable layout', () => {
	const editor = editorHarness(undefined, fixture(2, 2));
	const rootSignature = editor.routingSignature();
	editor.scope.groupPath = ['g0'];
	Object.assign(editor.scope, groupView(editor.scope.groupDocument, editor.scope.groupPath));
	expect(editor.routingSignature()).toBe(rootSignature);
	const counts = { ...editor.counts };
	editor.scope.edges = editor.scope.edges.map((e) => ({ ...e, selected: true, data: { reroutes: [{ x: 100, y: 200 }] } }));
	expect(editor.routingSignature()).toBe(rootSignature);
	expect(editor.counts).toEqual(counts);
	const gain = editor.scope.nodes.find((n) => n.type === 'gain')!;
	gain.data.gainDb = 6;
	const changedData = editor.routingSignature();
	expect(changedData).not.toBe(rootSignature);
	expect(editor.counts.expansions).toBe(counts.expansions + 1);
	expect(editor.getSnapshot().nodes.filter((n) => n.data.gainDb === 6)).toHaveLength(2);
	editor.scope.edges[0] = { ...editor.scope.edges[0], targetHandle: 'ch2' };
	const rewired = editor.routingSignature();
	expect(rewired).not.toBe(changedData);
	editor.scope.nodes.push({ id: 'added', type: 'gain', data: { gainDb: 0, bypassed: false }, position: { x: 100, y: 100 } });
	const added = editor.routingSignature();
	expect(added).not.toBe(rewired);
	editor.scope.nodes = editor.scope.nodes.filter((n) => n.id !== 'added');
	expect(editor.routingSignature()).toBe(rewired);
	const doc = structuredClone(editor.scope.groupDocument);
	const copy = copyDefinition(doc, 'leaf', true);
	const other = scopeAt(doc, []).nodes[1];
	if (other.kind !== 'group') throw new Error('Expected group');
	other.data.definition = copy;
	const copied = definition(doc, copy).nodes[0];
	if (copied.kind !== 'gain') throw new Error('Expected gain');
	copied.data.gainDb = 9;
	editor.scope.groupDocument = doc;
	expect(editor.routingSignature()).not.toBe(rewired);
	const validations = editor.counts.validations;
	editor.scope.groupLibrary = structuredClone(editor.scope.groupLibrary);
	editor.routingSignature();
	expect(editor.counts.validations).toBe(validations + 1);
	// An invalid edit must still be rejected on every attempt, including explicit saves.
	editor.scope.edges[0] = { ...editor.scope.edges[0], target: 'missing' };
	expect(editor.routingSignature()).toBe('');
	expect(editor.routingSignature()).toBe('');
	expect(() => editor.getSnapshot()).toThrow('Missing node');
});
